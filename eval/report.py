"""Combine answers, judges and human labels into eval/results/report.md.   uv run python eval/report.py"""
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from metrics import citation_coverage, mean, percentile

GOLD, OUT = Path("eval/gold.jsonl"), Path("eval/results")
LABEL_SOURCES = [("human (Pranav, blind)", Path("eval/human_labels.jsonl")),
                 ("Claude (assistant, NOT a human)", Path("eval/assistant_labels.jsonl"))]
MODES, JUDGES = ("hybrid+rerank", "hybrid+rerank_v2", "dense"), ("local", "haiku")


def load(path: Path) -> dict:
    return {r["id"]: r for r in map(json.loads, path.open(encoding="utf-8"))} if path.exists() else {}


def pct(x: float) -> str:
    return "–" if math.isnan(x) else f"{100 * x:.0f}%"


def gold_in_sources(g: dict, answer: dict) -> bool:
    """Recomputed from the current gold (stored values can be stale after a documented gold change)."""
    return bool(set(g["gold"]) & {s["article_key"] for s in answer["sources"]})


def kappa(a: list[bool], b: list[bool]) -> float:
    """Cohen's kappa: agreement corrected for chance (1 = perfect, 0 = chance level)."""
    n = len(a)
    if n == 0:
        return float("nan")
    po = sum(x == y for x, y in zip(a, b)) / n
    pa, pb = sum(a) / n, sum(b) / n
    pe = pa * pb + (1 - pa) * (1 - pb)
    return 1.0 if pe == 1 else (po - pe) / (1 - pe)


def generation_rows(gold: dict, answers: dict, judged: dict, subset=None) -> dict:
    ids = [i for i in answers if subset is None or subset(gold[i])]
    answerable = [i for i in ids if gold[i]["gold"]]
    unanswerable = [i for i in ids if not gold[i]["gold"]]
    answered = [i for i in answerable if not answers[i]["abstained"]]
    j = [judged[i] for i in answered if i in judged and "correct" in judged[i]]
    totals = [answers[i]["ms_retrieve"] + answers[i]["ms_generate"] for i in ids]
    return {
        "answerable": len(answerable),
        "gold in sources": mean(float(gold_in_sources(gold[i], answers[i])) for i in answerable),
        "false abstention": mean(float(answers[i]["abstained"]) for i in answerable),
        "faithfulness": mean(r.get("faithfulness") for r in j),
        "correct (answered)": mean(float(r["correct"]) for r in j),
        "correct (all answerable)": sum(r["correct"] for r in j) / len(answerable) if answerable else float("nan"),
        "complete (answered)": mean(float(r["complete"]) for r in j),
        "citation coverage": mean(citation_coverage(answers[i]["answer"]) for i in answered),
        "invalid citations": sum(len(answers[i]["invalid_citations"]) for i in ids),
        "correct abstention (unanswerable)": mean(float(answers[i]["abstained"]) for i in unanswerable),
        "p50 latency": percentile(totals, 0.5), "p95 latency": percentile(totals, 0.95),
    }


def main() -> None:
    gold = load(GOLD)
    answers = {m: load(OUT / f"answers_{m}.jsonl") for m in MODES}
    judges = {(j, m): load(OUT / f"judge_{j}_{m}.jsonl") for j in JUDGES for m in MODES}
    md = ["# Evaluation report", "", "Generated by `eval/report.py`. Retrieval details: `retrieval_summary.md`.", ""]

    # --- judge vs reference labels (decides which judge we trust) -----------------------------------
    trusted, best, trusted_by = "local", -1.0, None
    for source, path in LABEL_SOURCES:
        labels = load(path)
        if not labels:
            continue
        md += [f"## Judges vs. labels by {source}", "",
               f"{len(labels)} answers (hybrid+rerank), labelled before reading any judge output.", "",
               "| Judge | Faithful agree | Correct agree | Complete agree | Correct κ | Complete κ |",
               "|---|---|---|---|---|---|"]
        for jname in JUDGES:
            jr = judges[(jname, "hybrid+rerank")]
            ids = [i for i in labels if i in jr and "correct" in jr[i]]
            if not ids:
                continue
            judged = {i: {"faithful": jr[i]["faithfulness"] == 1.0, "correct": jr[i]["correct"],
                          "complete": jr[i]["complete"]} for i in ids}
            agree = {k: mean(float(judged[i][k] == labels[i][k]) for i in ids) for k in ("faithful", "correct", "complete")}
            kc = kappa([judged[i]["correct"] for i in ids], [labels[i]["correct"] for i in ids])
            km = kappa([judged[i]["complete"] for i in ids], [labels[i]["complete"] for i in ids])
            md.append(f"| {jname} ({jr[ids[0]]['model']}) | {pct(agree['faithful'])} | {pct(agree['correct'])} | "
                      f"{pct(agree['complete'])} | {kc:.2f} | {km:.2f} |")
            score = sum(agree.values())
            if trusted_by in (None, source) and score > best:
                trusted, best, trusted_by = jname, score, source
        rates = {k: mean(float(r[k]) for r in labels.values() if k in r)
                 for k in ("faithful", "correct", "complete", "citations_right")}
        md += ["", (f"Label rates ({source}): faithful {pct(rates['faithful'])}, correct {pct(rates['correct'])}, "
               f"complete {pct(rates['complete'])}, **citations right {pct(rates['citations_right'])}** "
               "(judges do not measure citation accuracy)."), ""]
    if trusted_by:
        md += [f"**Numbers below use the `{trusted}` judge** (best agreement with labels by {trusted_by}).", ""]

    # --- generation metrics per retrieval mode -------------------------------------------------------
    for title, subset in (("All 80 questions", None), ("Unseen during development (67)", lambda g: not g["dev_seen"])):
        md += [f"## Answer quality: {title}", ""]
        cols = [m for m in MODES if answers[m]]
        rows = {m: generation_rows(gold, answers[m], judges[(trusted, m)], subset) for m in cols}
        md += ["| Metric | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
        for key in next(iter(rows.values())):
            vals = [rows[m][key] for m in cols]
            fmt = (lambda v: f"{v:.0f} ms") if "latency" in key else (lambda v: str(v)) if key in (
                "answerable", "invalid citations") else pct
            md.append(f"| {key} | " + " | ".join(fmt(v) for v in vals) + " |")
        md.append("")

    # --- failure buckets (production mode) -------------------------------------------------------------
    a, jr = answers["hybrid+rerank"], judges[(trusted, "hybrid+rerank")]
    buckets: dict[str, list[str]] = {}
    for i, g in gold.items():
        if i not in a:
            continue
        x = a[i]
        tags = []
        if g["gold"]:
            if not gold_in_sources(g, x):
                tags.append("retrieval miss (gold article not among the 5 sources)")
            if x["abstained"]:
                tags.append("false abstention" if gold_in_sources(g, x) else "abstained (gold not retrieved)")
            r = jr.get(i, {})
            if "correct" in r:
                if not r["correct"]:
                    tags.append("incorrect")
                elif not r["complete"]:
                    tags.append("correct but incomplete")
                if r.get("faithfulness") is not None and r["faithfulness"] < 1:
                    tags.append("unfaithful claim(s)")
            coverage = None if x["abstained"] else citation_coverage(x["answer"])   # recomputed, not stored
            if coverage is not None and coverage < 1:
                tags.append("citation coverage < 100%")
        elif not x["abstained"]:
            tags.append("answered an unanswerable question")
        if x["invalid_citations"]:
            tags.append("invalid citation")
        for t in tags:
            buckets.setdefault(t, []).append(i)
    md += ["## Failure buckets (hybrid+rerank)", "", "| Bucket | Count | Questions |", "|---|---|---|"]
    for t, ids in sorted(buckets.items(), key=lambda kv: -len(kv[1])):
        md.append(f"| {t} | {len(ids)} | {', '.join(ids)} |")
    (OUT / "report.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
