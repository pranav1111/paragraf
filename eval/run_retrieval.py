"""Retrieval evaluation: every mode on every answerable gold question (no LLM involved).

    uv run python eval/run_retrieval.py      → eval/results/retrieval_<mode>.jsonl + retrieval_summary.md
"""
import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from metrics import hit_at_k, mean, percentile, recall_at_k, reciprocal_rank, unique

from paragraf.retrieve import MODES, Retriever

GOLD, OUT = Path("eval/gold.jsonl"), Path("eval/results")
DEPTH = 10                                           # evaluate deeper than the 5 sources we serve


def score(rows: list[dict]) -> dict:
    return {"n": len(rows),
            "Hit@1": mean(r["hit1"] for r in rows), "Recall@5": mean(r["r5"] for r in rows),
            "Recall@10": mean(r["r10"] for r in rows), "MRR": mean(r["rr"] for r in rows),
            "p50 ms": percentile([r["ms"] for r in rows], 0.5)}


def table(title: str, results: dict[str, list[dict]]) -> str:
    lines = [f"### {title}", "", "| Mode | n | Hit@1 | Recall@5 | Recall@10 | MRR | p50 latency |",
             "|---|---|---|---|---|---|---|"]
    for mode, rows in results.items():
        s = score(rows)
        lines.append(f"| {mode} | {s['n']} | {s['Hit@1']:.2f} | {s['Recall@5']:.2f} | {s['Recall@10']:.2f} | "
                     f"{s['MRR']:.2f} | {s['p50 ms']:.0f} ms |")
    return "\n".join(lines) + "\n"


def main() -> None:
    gold = [json.loads(line) for line in GOLD.open(encoding="utf-8")]
    answerable = [g for g in gold if g["gold"]]
    OUT.mkdir(parents=True, exist_ok=True)
    retriever = Retriever()
    retriever.search("warm-up")
    results: dict[str, list[dict]] = {}
    for mode in MODES:
        rows = []
        for g in answerable:
            start = time.perf_counter()
            hits = retriever.search(g["question"], mode=mode, top_k=DEPTH)
            ms = (time.perf_counter() - start) * 1000
            ranked, gs = unique(h.article_key for h in hits), set(g["gold"])
            rows.append({"id": g["id"], "type": g["type"], "lang": g["lang"], "dev_seen": g["dev_seen"],
                         "gold": g["gold"], "ranked": ranked, "hit1": hit_at_k(ranked, gs, 1),
                         "r5": recall_at_k(ranked, gs, 5), "r10": recall_at_k(ranked, gs, 10),
                         "rr": reciprocal_rank(ranked, gs), "ms": round(ms)})
        results[mode] = rows
        (OUT / f"retrieval_{mode}.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))
        print(f"{mode:14} done")

    parts = ["# Retrieval results\n",
             (f"Gold set: {len(answerable)} answerable questions; metrics at article level, "
              "language-free (finding the DE or EN version counts). Generated by `eval/run_retrieval.py`.\n"),
             table("All answerable questions", results),
             table("Unseen during development (dev_seen = false)",
                   {m: [r for r in rows if not r["dev_seen"]] for m, rows in results.items()})]
    for qtype in ("direct", "paraphrase", "exact_ref", "cross_law"):
        parts.append(table(f"Type: {qtype}", {m: [r for r in rows if r["type"] == qtype] for m, rows in results.items()}))
    parts.append(table("German questions", {m: [r for r in rows if r["lang"] == "de"] for m, rows in results.items()}))
    (OUT / "retrieval_summary.md").write_text("\n".join(parts), encoding="utf-8")
    print("\n" + "\n".join(parts[2:4]))


if __name__ == "__main__":
    main()
